def test_anydoc_is_told_to_reject_ocr_so_no_unredacted_byte_leaves_the_worker(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """ADR 0020's line applied to the converter. Conversion runs **before** the seam, so
    its input is the document exactly as the reader uploaded it — and under `anydoc`'s
    other arm, `"hosted"`, the library posts those bytes to `api.firecrawl.dev`.

    **Under that arm `anydoc` is an external service, so it is replaced behind the
    adapter that calls it** (`[TEST3]`) and the case asserts what crossed: the format
    named and the arm taken, read off the call the shipping `converted` actually made.
    Nothing of this tier is replaced — `converted` is the interface a caller uses and it
    is the real one.

    A behavioural case cannot be had here, which is why this one records the call.
    Probed on 20 September 2026 against `firecrawl-anydoc` 0.2.4: a `.docx` holding
    nothing but a bitmap — the nearest thing to a document wanting OCR — converts to the
    empty string under `"reject"` and under `"hosted"` alike, so no document tells the
    two arms apart. The only thing that would is a route to the network, which is the
    very thing being forbidden.

    The two literals above the call keep the constant honest and record that the library
    offers a second arm at all: a case reading only the library's own default would go
    on passing the day a patch release moved it.
    """
    import anydoc

    assert OCR_ANSWER == "reject"
    assert set(get_args(anydoc.Ocr)) == {"reject", "hosted"}
    assert signature(anydoc.to_markdown_bytes).parameters["ocr"].default == OCR_ANSWER

    asked: list[tuple[object, object, dict[str, object]]] = []

    # The library names its second parameter `format`; the adapter passes it
    # positionally, so the recorder is free to call it something that is not a builtin.
    def record(data: bytes, as_format: object = None, **rest: object) -> str:
        asked.append((as_format, rest.pop("ocr", None), rest))
        return "# Recorded"

    monkeypatch.setattr(anydoc, "to_markdown_bytes", record)

    assert converted(b"a zip nothing reads", DOCX_MEDIA_TYPE) == "# Recorded"
    assert asked == [("docx", "reject", {})]


