def test_the_timeout_is_the_seams_ms_per_page_times_the_pages_and_a_margin() -> None:
    """The derivation, written down rather than recomputed (`[TEST9]`). S0 measured the
    seam at 2841 ms a page on the worker image — the slowest of its three readings,
    because this is a ceiling — and the margin is what a document is given whatever its
    length: the one-off model load a process's first document pays, the conversion in
    front of the seam, and the engine's work around both.
    """
    assert SEAM_MS_PER_PAGE == 2841
    assert TIMEOUT_MARGIN_MS == 30_000
    assert timeout_for(1).total_seconds() == pytest.approx(32.841)
    assert timeout_for(12).total_seconds() == pytest.approx(64.092)
    assert timeout_for(12) - timeout_for(11) == timeout_for(1) - timeout_for(0)


def test_a_pdfs_pages_are_read_and_the_other_types_measured_against_s0s_page() -> None:
    """A PDF is the one type that carries a page count, and it is read out of the
    header before the conversion the ceiling is for — taking it from a conversion would
    mean knowing how long to allow only once the conversion had already returned.

    The other three have no pages, so the estimate is the landed copy's byte length over
    the 2,488-byte page S0 timed itself against. It **over-counts** a `.docx`, whose
    bytes are a zip holding images and styles as well as text, and so errs long — which
    is the right direction for a ceiling.
    """
    assert pages_of(fixture_bytes("rate-card.pdf"), PDF_MEDIA_TYPE) == 1
    assert pages_of(b"", "text/markdown") == 1
    assert pages_of(b"a" * 2488, "text/markdown") == 1
    assert pages_of(b"a" * 2489, "text/markdown") == 2
    # The `.docx` fixture is two paragraphs, a list and a table — a page of text in a
    # zip of thirty-six kilobytes, which this counts as fifteen.
    assert pages_of(fixture_bytes("expenses-policy.docx"), DOCX_MEDIA_TYPE) == 15


def test_a_document_that_runs_past_its_ceiling_is_quarantined_and_the_run_finishes(
    host: Host,
) -> None:
    """The ceiling is cooperative and per document, so a conversion that sticks is that
    document's quarantine and never the binding's: the run finishes, writes nothing
    under the document's normalised key, and names the deadline as what refused it.

    *Slow* is made by the ceiling rather than by the document, and deliberately. The
    shipped allowance is thirty-three seconds for a single page against a conversion
    that costs single-digit milliseconds, so a document slow enough to breach it on one
    machine would be a document that breached nothing on the next — and a case that
    waited for one would be a case about this laptop. A ceiling of nothing is the same
    fact stated in a way every machine agrees on.
    """
    bucket = a_bucket_holding_both()

    answer = read_the_copies(host, bucket, (THE_INVOICE,), ms_per_page=0, margin_ms=0)

    assert quarantine_of(answer) == {AN_INVOICE_ID: "DeadlineExceededError"}
    assert answer.documents == ()
    assert bucket.writes == []


def test_the_same_document_under_the_shipped_ceiling_lands(host: Host) -> None:
    """The control the case above needs (`[TEST7]`): the same document, the same run,
    the ceiling this tier ships — and it lands. Without this, a quarantine that had
    nothing to do with the deadline would read as a timeout working.
    """
    bucket = a_bucket_holding_both()

    answer = read_the_copies(host, bucket, (THE_INVOICE,))

    assert answer.quarantined == ()
    assert text_of(answer, AN_INVOICE_ID) == AN_INVOICE_REDACTED


