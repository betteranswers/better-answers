"""The one memoised function: a landed copy converted, redacted and cut into chunks
(`[TEST1]`, `[TEST3]`, `[TEST7]`, `[TEST9]`).

Driven through `better_answers_worker.pipeline`'s own interface, over a real engine and
a real detector, because everything these cases are about is what the memo does between
two runs — and a memo nobody ran is a decoration.

**No database.** Nothing here writes a row: the memo lives in the binding's store on
disk and the chunk rows are the wave after this one. The pool a run would use is built
lazily and never asked for, which is why the bootstrap below names an address that does
not answer — a case that quietly opened a connection would fail there rather than pass
here.

**The object store is the one external service, and it is replaced behind its adapter**
with the dictionary below (`[TEST3]`). The bytes of a landed copy are what the estate's
bucket would hand back; what the cases are about is which key they were asked for and
which key the normalised copy went under, and a bucket cannot say that more clearly than
a dictionary can.

**The converters are real and so are their documents.** `anydoc` and `pdf-inspector` run
here exactly as they run in the image, over the committed fixtures in
`tests/fixtures/conversion/` — because what a converter makes of a real `.docx` or a
real PDF is the whole question, and a document a case generated would be a document
generated by whichever writer the case imported. The first act that proved both of them
*on the worker image, under the engine's runtime* is the case named
`test_both_converters_hold_on_the_image_under_the_engines_own_runtime` in
`tests/test_image.py`, whose docblock carries its four readings and the memory beside
them.

**What is written down here, and why it is not derived.** The redacted text of every
document, the categories the seam raises, the version string and every chunk boundary
are literals (`[TEST9]`). The two markdown documents' were read out of the seam on 11
September 2026 at `rule_version` 1 and the converted fixtures' on 20 September 2026 at
`rule_version` 2, each at the detector pin this tier ships; a case that asked the seam
or the converter what it answered would agree with either answering anything.
"""

