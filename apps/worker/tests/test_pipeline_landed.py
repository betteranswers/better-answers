def test_a_pdf_with_a_page_that_has_no_text_layer_is_quarantined_whole(
    host: Host,
) -> None:
    """Whole, and never half-converted: a document with the scanned pages missing would
    be an address space with a hole in it, and every citation into the pages that did
    convert would point into a document nobody can see the whole of.

    The name is the converter's own, because an Admin deciding whether the binding needs
    OCR has to be able to tell a scan from a corrupt upload — and that share is the
    trigger that replaced docling's (ADR 0013, amended 20/09/2026).
    """
    scan = a_landed_document(A_SCAN_ID, media_type=PDF_MEDIA_TYPE)
    bucket = ABucket(
        {
            scan.original_key: fixture_bytes("scanned-invoice.pdf"),
            THE_DELIVERY_NOTE.original_key: A_DELIVERY_NOTE.encode(),
        }
    )

    answer = read_the_copies(host, bucket, (scan, THE_DELIVERY_NOTE))

    assert quarantine_of(answer) == {A_SCAN_ID: "NeedsOcrError"}
    assert [document.source_document_id for document in answer.documents] == [
        A_DELIVERY_NOTE_ID
    ]
    assert bucket.writes == [THE_DELIVERY_NOTE.normalised_key]


