describe("the status of a concept", () => {
  it.each([
    ["changed-since-checked", "Changed since verified"],
    ["out-of-date", "Out of date"],
    ["draft", "Draft"],
    ["deprecated", "Deprecated"],
  ] as const)("reads %s as %s", (status, words) => {
    const block = drawn(anIssuedConcept({ trust: { ...VERIFIED_BY_PRIYA, status } }));

    expect(wordsOf(block, "Status")).toBe(words);
  });

  it("tints the past review date of an out-of-date concept", () => {
    const current = drawn(anIssuedConcept());
    const currentColour = valueOf(current, "Review by").firstElementChild?.className;
    cleanup();

    const block = drawn(
      anIssuedConcept({
        trust: { ...VERIFIED_BY_PRIYA, status: "out-of-date" },
        trustWords: "Out of date",
        frontmatter: { title: "Safeguarding", type: "Sector", stale_after: "2026-01-15" },
      }),
    );

    expect(wordsOf(block, "Status")).toBe("Out of date");
    expect(wordsOf(block, "Review by")).toBe("15 January 2026");
    expect(valueOf(block, "Review by").firstElementChild?.className).not.toBe(currentColour);
  });

  it("says when no review date is set", () => {
    const block = drawn(
      anIssuedConcept({ frontmatter: { title: "Safeguarding", type: "Sector" } }),
    );

    expect(wordsOf(block, "Review by")).toBe("Not set");
  });
});

describe("the generation of a concept", () => {
  it("reads a person's generation as a person", () => {
    const block = drawn(
      anIssuedConcept({
        frontmatter: {
          title: "Safeguarding",
          type: "Sector",
          generated: [{ by: "human:01JBZ6Q2V7Y9K3M5N8P0R2T4W6", at: "2026-02-10" }],
        },
      }),
    );

    expect(linesOf(block, "Generated by")).toEqual(["A person", "10 February 2026"]);
  });

  it("says when nothing is recorded", () => {
    const block = drawn(
      anIssuedConcept({ frontmatter: { title: "Safeguarding", type: "Sector" } }),
    );

    expect(wordsOf(block, "Generated by")).toBe("Not recorded");
  });
});

describe("the owner of a concept", () => {
  it("names the owner of its collection", () => {
    const block = drawn(anIssuedConcept());

    expect(linesOf(block, "Owner")).toEqual(["Ifan Morgan", "Owner of Sectors"]);
  });

  it("names the collection by its display name", () => {
    const block = drawn(anIssuedConcept({ collection: "multi-academy-trusts" }));

    expect(linesOf(block, CONCEPT_WORDS.titleBlock.owner)).toEqual([
      "Ifan Morgan",
      CONCEPT_WORDS.titleBlock.ownerOf("Multi academy trusts"),
    ]);
  });

  it("names the concept's own owner with no collection line", () => {
    const block = drawn(
      anIssuedConcept({
        owner: {
          personId: aPersonId("01JBZ6Q2V7Y9K3M5N8P0R2T4W6"),
          name: "Priya Shah",
          via: "concept",
        },
      }),
    );

    expect(linesOf(block, "Owner")).toEqual(["Priya Shah"]);
  });

  it("says when nobody owns it", () => {
    const block = drawn(anIssuedConcept({ owner: null }));

    expect(wordsOf(block, "Owner")).toBe("No owner");
  });
});

describe("the sources and use of a concept", () => {
  it("counts no sources, with nowhere to go", () => {
    const block = drawn(anIssuedConcept({ evidence: [] }));

    expect(wordsOf(block, "Sources")).toBe("0");
    expect(block.queryByRole("button")).toBeNull();
  });

  it("takes the reader to the sources when there are some", () => {
    const toSources = vi.fn<() => void>();
    const block = drawn(anIssuedConcept({ evidence: [{ source: "Records policy" }] }), toSources);

    fireEvent.click(block.getByRole("button", { name: "Go to 1 source" }));

    expect(toSources).toHaveBeenCalledOnce();
  });

  it.each([
    ["1 guide · 1 answer", { guides: 1, answers: 1 }],
    ["3 guides · 12 answers", { guides: 3, answers: 12 }],
    ["2 answers", { guides: 0, answers: 2 }],
  ])("shows %s", (words, usedIn) => {
    const block = drawn(anIssuedConcept({ usedIn }));

    expect(wordsOf(block, "Used in")).toBe(words);
  });

  it("counts no zero when nothing uses it", () => {
    const block = drawn(anIssuedConcept({ usedIn: { guides: 0, answers: 0 } }));

    expect(wordsOf(block, "Used in")).not.toMatch(/\b0\b/u);
  });
});

describe("the other fields of a concept", () => {
  it("leaves the row out when the file holds nothing else", () => {
    const block = drawn(anIssuedConcept());

    expect(block.queryByText("Other fields", { selector: "dt" })).toBeNull();
  });

  it("hides an unknown key until the reader opens the row", () => {
    const block = drawn(
      anIssuedConcept({
        frontmatter: {
          title: "Safeguarding",
          type: "Sector",
          bid_reference: "NB-LMS-2026-014",
          regions: ["North East", "Yorkshire"],
        },
      }),
    );
    const fields = valueOf(block, "Other fields");
    const details = fields.querySelector("details");

    expect(details?.open).toBe(false);

    fireEvent.click(within(fields).getByText("2 fields"));

    expect(details?.open).toBe(true);
    expect(within(fields).getByText("bid_reference").nextElementSibling?.textContent).toBe(
      "NB-LMS-2026-014",
    );
    expect(within(fields).getByText("regions").nextElementSibling?.textContent).toBe(
      "North East, Yorkshire",
    );
  });
});
