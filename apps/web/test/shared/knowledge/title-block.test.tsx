import { cleanup, fireEvent, render, screen, within } from "@testing-library/react";
import { afterEach, describe, expect, it, vi } from "vitest";

import { CONCEPT_WORDS } from "@/shared/knowledge/concept-words.ts";
import { TitleBlock } from "@/shared/knowledge/title-block.tsx";
import {
  anIssuedConcept,
  aPersonId,
  PRIYA,
  THE_EXTRACTOR,
  VERIFIED_BY_PRIYA,
} from "@test/knowledge/search-answers.ts";

afterEach(cleanup);

type Concept = Parameters<typeof TitleBlock>[0]["concept"];

const UNVERIFIED: Concept["trust"] = {
  tier: "unverified",
  status: "current",
  verifiedBy: null,
  verifiedAt: null,
  rider: null,
};

const drawn = (concept: Concept, onGoToSources: () => void = () => undefined) => {
  render(<TitleBlock concept={concept} onGoToSources={onGoToSources} />);
  return within(screen.getByRole("complementary", { name: "About this concept" }));
};

type Block = ReturnType<typeof drawn>;

const valueOf = (block: Block, label: string): HTMLElement => {
  const value = block.getByText(label, { selector: "dt" }).nextElementSibling;
  if (!(value instanceof HTMLElement)) throw new Error(`no value follows ${label}`);
  return value;
};

const wordsOf = (block: Block, label: string): string => valueOf(block, label).textContent;

const leavesOf = (node: Element): readonly string[] =>
  node.childElementCount === 0
    ? [node.textContent].filter((words) => words !== "")
    : Array.from(node.children).flatMap(leavesOf);

/** The words of a cell line by line, as the reader sees them: the value, then what sits under it. */
const linesOf = (block: Block, label: string): readonly string[] => leavesOf(valueOf(block, label));

describe("the title block of a concept a person verified", () => {
  it("answers every question a reader asks before reusing it", () => {
    const block = drawn(
      anIssuedConcept({
        evidence: [
          { source: "SCP tender 2025.pdf", at: "p.4" },
          { source: "Working Together to Safeguard Children 2023", at: "ch.2" },
        ],
      }),
    );

    expect(wordsOf(block, "Trust")).toBe("Verified by Priya Shah · 3 March 2026");
    expect(wordsOf(block, "Reference")).toBe(
      "knowledge/sectors/safeguarding-children-partnerships",
    );
    expect(linesOf(block, "Generated by")).toEqual(["okf-extract/0.4", "10 February 2026"]);
    expect(linesOf(block, CONCEPT_WORDS.titleBlock.checkedBy)).toEqual([
      "Priya Shah",
      "3 March 2026",
    ]);
    expect(linesOf(block, CONCEPT_WORDS.titleBlock.history)).toEqual([
      CONCEPT_WORDS.titleBlock.automatically,
      "12 February 2026",
    ]);
    expect(block.queryByText(CONCEPT_WORDS.titleBlock.status, { selector: "dt" })).toBeNull();
    expect(wordsOf(block, "Review by")).toBe("3 September 2026");
    expect(linesOf(block, "Owner")).toEqual(["Ifan Morgan", "Owner of Sectors"]);
    expect(wordsOf(block, "Sources")).toBe("2");
    expect(wordsOf(block, "Used in")).toBe(CONCEPT_WORDS.titleBlock.used(3, 12));
  });

  it("lists earlier checks newest first, each with who and when", () => {
    const block = drawn(
      anIssuedConcept({
        verifications: [
          PRIYA,
          { ...PRIYA, name: "Hannah Doyle", at: "2026-02-20T09:00:00.000Z" },
          THE_EXTRACTOR,
        ],
      }),
    );

    const earlier = within(valueOf(block, CONCEPT_WORDS.titleBlock.history)).getAllByRole(
      "listitem",
    );

    expect(earlier.map(leavesOf)).toEqual([
      ["Hannah Doyle", "20 February 2026"],
      [CONCEPT_WORDS.titleBlock.automatically, "12 February 2026"],
    ]);
  });

  it("names a former member for a checker with no name", () => {
    const block = drawn(anIssuedConcept({ verifications: [{ ...PRIYA, name: null }] }));

    expect(linesOf(block, CONCEPT_WORDS.titleBlock.checkedBy)).toEqual([
      "A former member",
      "3 March 2026",
    ]);
  });
});

describe("the title block of a concept a machine verified", () => {
  it("says it was checked automatically, and on which day", () => {
    const block = drawn(
      anIssuedConcept({
        trust: {
          tier: "machine-confirmed",
          status: "current",
          verifiedBy: null,
          verifiedAt: THE_EXTRACTOR.at,
          rider: null,
        },
        trustWords: "Verified automatically",
        verifications: [THE_EXTRACTOR],
      }),
    );

    expect(wordsOf(block, "Trust")).toBe("Verified automatically · 12 February 2026");
    expect(linesOf(block, CONCEPT_WORDS.titleBlock.checkedBy)).toEqual([
      CONCEPT_WORDS.titleBlock.automatically,
      "12 February 2026",
    ]);
    expect(wordsOf(block, CONCEPT_WORDS.titleBlock.history)).toBe(
      CONCEPT_WORDS.titleBlock.noEarlierChecks,
    );
  });
});

describe("the title block of a concept nobody has verified", () => {
  it("says it has not been checked", () => {
    const block = drawn(
      anIssuedConcept({ trust: UNVERIFIED, trustWords: "Unverified", verifications: [] }),
    );

    expect(wordsOf(block, "Trust")).toBe("Unverified");
    expect(wordsOf(block, CONCEPT_WORDS.titleBlock.checkedBy)).toBe(
      CONCEPT_WORDS.titleBlock.notCheckedYet,
    );
    expect(wordsOf(block, CONCEPT_WORDS.titleBlock.history)).toBe(
      CONCEPT_WORDS.titleBlock.noEarlierChecks,
    );
  });
});

